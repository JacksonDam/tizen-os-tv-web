export type RowStyle =
  | 'category'            // root-page category (Picture, Sound, ...)
  | 'title'               // opens a sub-page, or launches something (see `action`)
  | 'title.value'         // title + current value on a second line; Enter opens `groups` or a picker
  | 'title.switch'        // On/Off switch
  | 'title.slider.value'  // slider with numeric value
  | 'option'              // a selectable option row inside a sub-page (radio-like)
  | 'title.icon'
  | 'button'

export type MenuOption = { value: string | number; label: string }

export type MenuItem = {
  id: string                 // the menu item id from the JSON, e.g. 'picturemode' ('<parent>/<value>' for option rows)
  title: string              // English
  style: RowStyle
  picker?: boolean           // true when the row opens the dropdown option list (ui popup.optionlist)
  options?: MenuOption[]     // for pickers, switches (Off/On) and option pages
  value?: string | number    // default/current value (an option value, a switch 0/1, or a slider number)
  valueText?: string         // the second line shown for title.value rows, when not derivable from options
  min?: number; max?: number; step?: number   // sliders
  format?: 'tint'            // slider value text: 'tint' shows G<n> below the midpoint, 0/0 at it, R<n> above
  disabled?: boolean         // visible but disabled on this TV (enable checker false)
  disabledReason?: string    // English message the TV shows when a disabled row is selected, if known
  action?: 'app' | 'none'    // 'app' = launches another application or gadget (no sub-page in this rebuild)
  ui?: string                // the TV's setting-ui style when Enter does something else than open a page, picker
                             // or switch: popup.reset, popup.changepin, page.balance, page.equalizer, page.menustyle,
                             // page.zoomposition, spin.time, spin.date, application, ui-gadget, page.ris.optionlist
  pinPrompt?: boolean        // the TV asks for the PIN first
  help?: string              // English help text (the side card), if any
  icon?: string              // category icon file name, for category rows only (public/tv/menu/menu_icon/)
  groups?: MenuItem[][]      // sub-page content: array of groups (each group is drawn as one rounded block)
  // web rebuild hooks (see src/screens/allsettings/extensions.ts):
  gadget?: string            // OK opens an in-panel page component (e.g. About TV)
  popup?: string             // OK opens a popup component drawn over the panel (e.g. the Auto Tuning confirmation)
  launch?: { app: string; args?: Record<string, string>; exitMenu?: boolean }  // OK starts a full-screen app
  live?: (values: Record<string, string | number>) => Partial<MenuItem>       // row state that follows other settings
}

